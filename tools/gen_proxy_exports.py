"""Generate linker pragmas that forward every export of a system DLL to the real copy in System32.

The forwarder uses the \\\\.\\GLOBALROOT\\SystemRoot\\System32 path, so the loader resolves the real DLL even
though our proxy has the same name and sits in the game folder. Ordinals are preserved.

Usage: python -I gen_proxy_exports.py C:/Windows/System32/winhttp.dll ../src/proxy_exports.h
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pe_info import PE  # noqa: E402


def main():
    src, out = sys.argv[1], sys.argv[2]
    dll = os.path.basename(src)
    module = os.path.splitext(dll)[0]
    target = "\\\\\\\\.\\\\GLOBALROOT\\\\SystemRoot\\\\System32\\\\" + dll
    lines = [
        "// Generated by tools/gen_proxy_exports.py from " + src.replace("\\", "/") + ". Do not edit.",
        "#pragma once",
        "",
    ]
    count = 0
    for e in PE(src).exports():
        if e["name"]:
            lines.append(
                f'#pragma comment(linker, "/export:{e["name"]}=\\"{target}\\".{e["name"]},@{e["ordinal"]}")')
        else:
            lines.append(
                f'#pragma comment(linker, "/export:__ord{e["ordinal"]}=\\"{target}\\".#{e["ordinal"]},@{e["ordinal"]},NONAME")')
        count += 1
    lines.append("")
    lines.append(f"#define PROXY_MODULE_NAME L\"{module}\"")
    lines.append(f"#define PROXY_EXPORT_COUNT {count}")
    lines.append("")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"wrote {count} forwards for {dll} -> {out}")


if __name__ == "__main__":
    main()
